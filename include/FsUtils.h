#pragma once

#include <Arduino.h>
#include <ArduinoJson.h>

// Атомарная запись JSON-документа в файл LittleFS.
//
// Документ сначала пишется во временный файл рядом с целевым (path + ".tmp"),
// и только после успешной записи переименовывается поверх целевого.
// Если питание пропадет в процессе — на флеше останется прежняя версия файла,
// а не обрезанный JSON, который потом не распарсится
//
// Возвращает true, если файл полностью записан и переименован
bool fs_write_json_atomic(const char *path, const JsonDocument &doc);
